import { describe, expect, test } from "vitest";
import { stringify } from "yaml";
import { generateCodeowners } from "../src/codeowners.ts";
import { type Config, parseConfig } from "../src/config.ts";
import type { Frontmatter } from "../src/schema.ts";
import { validFrontmatter } from "./helpers.ts";

type Member = { id: string; role: "senior" | "member"; areas?: string[]; handle?: string };

function config(members: Member[], areas: Record<string, string[]> = { api: ["api/**"] }): Config {
  const { config, issues } = parseConfig(stringify({ version: 1, team: { members }, areas }));
  if (!config) throw new Error(JSON.stringify(issues));
  return config;
}

const entry = (id: string, area: string, owner: string): Frontmatter => ({
  ...(validFrontmatter() as Frontmatter),
  id,
  area,
  owner,
});

const team: Member[] = [
  { id: "ana", role: "senior", areas: ["core"], handle: "@ana" },
  { id: "bo", role: "member", areas: ["api"], handle: "@acme/api-team" },
  { id: "cy", role: "member", areas: [], handle: "cy@example.com" },
];

describe("generateCodeowners", () => {
  test("seniors own the repo and config; area members own their folders", () => {
    const { text, issues } = generateCodeowners(config(team), []);
    expect(issues).toEqual([]);
    expect(text).toBe(
      [
        "# Generated by homeostat from homeostat.yaml and knowledge/. Do not edit; run `homeostat codeowners`.",
        "",
        "*                @ana",
        "/homeostat.yaml  @ana",
        "/knowledge/api/  @acme/api-team",
        "/knowledge/core/ @ana",
        "",
      ].join("\n"),
    );
  });

  test("an area nobody lists falls back to the seniors", () => {
    const { text } = generateCodeowners(config(team, { api: ["api/**"], web: ["web/**"] }), []);
    expect(text).toContain("/knowledge/web/  @ana\n");
  });

  test("core falls back to seniors too", () => {
    const members: Member[] = [
      { id: "ana", role: "senior", handle: "@ana" },
      { id: "bo", role: "member", areas: ["api"], handle: "@bo" },
    ];
    expect(generateCodeowners(config(members), []).text).toContain("/knowledge/core/ @ana\n");
  });

  test("an entry owner outside the area gets a line for that entry, after the folder line", () => {
    const { text } = generateCodeowners(config(team), [
      entry("x-rule", "api", "cy"),
      entry("y-rule", "api", "bo"),
    ]);
    const lines = text.split("\n");
    expect(lines).toContain("/knowledge/api/x-rule.md cy@example.com @acme/api-team");
    expect(text).not.toContain("y-rule");
    expect(lines.indexOf("/knowledge/api/x-rule.md cy@example.com @acme/api-team")).toBeGreaterThan(
      lines.findIndex((l) => l.startsWith("/knowledge/api/ ")),
    );
  });

  test("output is deterministic regardless of input order", () => {
    const a = generateCodeowners(config(team), [entry("b", "api", "cy"), entry("a", "core", "cy")]);
    const b = generateCodeowners(config(team), [entry("a", "core", "cy"), entry("b", "api", "cy")]);
    expect(a.text).toBe(b.text);
  });

  test("an owner without a handle is an error naming the member", () => {
    const members: Member[] = [
      { id: "ana", role: "senior", handle: "@ana" },
      { id: "bo", role: "member", areas: ["api"] },
    ];
    const { issues } = generateCodeowners(config(members), []);
    expect(issues).toEqual([
      expect.objectContaining({
        code: "codeowners.handle.missing",
        message: expect.stringContaining('"bo"'),
      }),
    ]);
  });

  test("a team with no seniors is an error, since nobody would own the config", () => {
    const { issues } = generateCodeowners(
      config([{ id: "bo", role: "member", handle: "@bo" }]),
      [],
    );
    expect(issues.map((i) => i.code)).toContain("codeowners.noSeniors");
  });
});

describe("member handle in homeostat.yaml", () => {
  test.each([
    "@dana",
    "@acme/platform",
    "dana@example.com",
    "@Dana Ruiz",
    "@Javier Gallostra Acín",
  ])("accepts %s", (handle) => {
    expect(() => config([{ id: "a", role: "senior", handle }])).not.toThrow();
  });

  test.each(["dana", "@", "@ a", "@a b ", "@a  b"])("rejects %s", (handle) => {
    expect(() => config([{ id: "a", role: "senior", handle }])).toThrow(/handle/);
  });
});
