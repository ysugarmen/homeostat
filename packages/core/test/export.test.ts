import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, test } from "vitest";
import { parseDocument } from "yaml";
import { exportRules } from "../src/export.ts";
import { BLOCK_START } from "../src/export-block.ts";
import { validate } from "../src/validate.ts";

const starter = new URL("../../../examples/starter-kb/", import.meta.url).pathname;

function entries() {
  const files: Record<string, string> = {};
  for (const f of readdirSync(starter, { recursive: true, encoding: "utf8" })) {
    if (f.endsWith(".md") || f.endsWith(".yaml")) files[f] = readFileSync(join(starter, f), "utf8");
  }
  delete files["README.md"];
  return validate(files).entries.map((e) => e.entry);
}

const ALL = ["claude", "cursor", "agents-md", "copilot"] as const;
const frontmatter = (text: string) =>
  parseDocument(/^---\n([\s\S]*?)\n---\n/.exec(text)?.[1] ?? "").toJS();

describe("exportRules", () => {
  test("only accepted entries, one owned file per area per tool", () => {
    const out = exportRules(entries(), ALL);
    expect(Object.keys(out.owned).sort()).toEqual([
      ".claude/rules/kbx/core.md",
      ".claude/rules/kbx/integrations.md",
      ".cursor/rules/kbx/core.mdc",
      ".cursor/rules/kbx/integrations.mdc",
      ".github/instructions/kbx/integrations.instructions.md",
    ]);
    const all = Object.values(out.owned).join("\n") + Object.values(out.blocks).join("\n");
    expect(all).not.toContain("use-design-tokens-for-colors"); // a candidate
    expect(out.ownedDirs).toEqual([
      ".claude/rules/kbx",
      ".cursor/rules/kbx",
      ".github/instructions/kbx",
    ]);
  });

  test("Claude: path-scoped areas get a paths list; core has no frontmatter", () => {
    const out = exportRules(entries(), ["claude"]);
    const integrations = out.owned[".claude/rules/kbx/integrations.md"] ?? "";
    expect(frontmatter(integrations)).toEqual({
      paths: ["services/integrations/**", "packages/http-client/**"],
    });
    expect(integrations).toContain("Generated by `kbx export`");
    expect(integrations).toContain("### Use the shared retry helper for outbound HTTP calls");
    expect(integrations).toContain("(kbx: outbound-http-retry-helper)");
    const core = out.owned[".claude/rules/kbx/core.md"] ?? "";
    expect(core.startsWith("<!-- Generated")).toBe(true);
  });

  test("Cursor: comma-separated globs and alwaysApply false; core always applies", () => {
    const out = exportRules(entries(), ["cursor"]);
    expect(frontmatter(out.owned[".cursor/rules/kbx/integrations.mdc"] ?? "")).toEqual({
      description: "Team rules (kbx) for integrations",
      globs: "services/integrations/**, packages/http-client/**",
      alwaysApply: false,
    });
    expect(frontmatter(out.owned[".cursor/rules/kbx/core.mdc"] ?? "")).toEqual({
      description: "Team rules (kbx) for all code",
      alwaysApply: true,
    });
  });

  test("Copilot: applyTo per scoped area; always-on rules in copilot-instructions.md", () => {
    const out = exportRules(entries(), ["copilot"]);
    expect(
      frontmatter(out.owned[".github/instructions/kbx/integrations.instructions.md"] ?? ""),
    ).toEqual({
      applyTo: "services/integrations/**,packages/http-client/**",
    });
    const block = out.blocks[".github/copilot-instructions.md"] ?? "";
    expect(block.startsWith(BLOCK_START)).toBe(true);
    expect(block).toContain("(kbx: redact-before-logging)");
    expect(block).not.toContain("outbound-http-retry-helper");
  });

  test("AGENTS.md: one block with every area and each rule's paths", () => {
    const block = exportRules(entries(), ["agents-md"]).blocks["AGENTS.md"] ?? "";
    expect(block).toContain("# Team rules (kbx) for all code");
    expect(block).toContain("# Team rules (kbx) for integrations");
    expect(block).toContain("Applies to: `services/integrations/**`, `packages/http-client/**`");
    expect(block.indexOf("all code")).toBeLessThan(block.indexOf("integrations"));
  });

  test("no accepted entries means empty blocks, so kbx's part is removed", () => {
    const out = exportRules([], ALL);
    expect(out.owned).toEqual({});
    expect(out.blocks).toEqual({ ".github/copilot-instructions.md": "", "AGENTS.md": "" });
  });
});
