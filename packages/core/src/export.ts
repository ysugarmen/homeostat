import { CORE_AREA } from "./check.ts";
import type { Entry } from "./entry.ts";
import { BLOCK_END, BLOCK_START } from "./export-block.ts";

export type ExportTarget = "claude" | "cursor" | "agents-md" | "copilot";

/** Folders kbx owns outright in a code repo; anything else in them is stale and removed. */
export const OWNED_DIRS: Record<Exclude<ExportTarget, "agents-md">, string> = {
  claude: ".claude/rules/kbx",
  cursor: ".cursor/rules/kbx",
  copilot: ".github/instructions/kbx",
};

/** Shared files where kbx only owns a marked block. */
export const BLOCK_FILES = {
  agentsMd: "AGENTS.md",
  copilot: ".github/copilot-instructions.md",
} as const;

export interface ExportOutput {
  /** Files under OWNED_DIRS, written whole. */
  owned: Record<string, string>;
  /** The owned folders of the selected targets. */
  ownedDirs: string[];
  /** Shared file → the marked block to put in it; an empty string means remove kbx's block. */
  blocks: Record<string, string>;
}

const NOTICE =
  "<!-- Generated by `kbx export` from the team knowledge base. Do not edit: change the entry in the KB. -->";

const GLOBAL = new Set(["**", "**/*"]);

interface Group {
  area: string;
  entries: Entry[];
  /** Union of the entries' scopes; empty when any entry applies everywhere. */
  globs: string[];
}

/** Accepted entries by area, core first, best score first within an area. */
function groups(entries: readonly Entry[]): Group[] {
  const byArea = new Map<string, Entry[]>();
  for (const e of entries) {
    if (e.frontmatter.status !== "accepted") continue;
    byArea.set(e.frontmatter.area, [...(byArea.get(e.frontmatter.area) ?? []), e]);
  }
  return [...byArea]
    .sort(([a], [b]) => (a === CORE_AREA ? -1 : b === CORE_AREA ? 1 : a.localeCompare(b)))
    .map(([area, list]) => {
      const sorted = [...list].sort(
        (a, b) =>
          b.frontmatter.score - a.frontmatter.score ||
          a.frontmatter.id.localeCompare(b.frontmatter.id),
      );
      const scopes = sorted.flatMap((e) => e.frontmatter.scope);
      const global = area === CORE_AREA || scopes.some((g) => GLOBAL.has(g));
      return { area, entries: sorted, globs: global ? [] : [...new Set(scopes)] };
    });
}

function rule(e: Entry, withScope: boolean): string {
  const fm = e.frontmatter;
  const scope =
    withScope && !fm.scope.every((g) => GLOBAL.has(g))
      ? `\nApplies to: ${fm.scope.map((g) => `\`${g}\``).join(", ")}`
      : "";
  return `### ${fm.title}\n${e.sections.rule ?? ""}\n\nWhy: ${e.sections.why ?? ""}${scope}\n\n(kbx: ${fm.id})`;
}

const heading = (area: string) =>
  area === CORE_AREA ? "Team rules (kbx) for all code" : `Team rules (kbx) for ${area}`;

const body = (g: Group, withScope = false) =>
  `# ${heading(g.area)}\n\n${g.entries.map((e) => rule(e, withScope)).join("\n\n")}\n`;

/** YAML double-quoted scalar, for globs that may contain `*`, `{` or `,`. */
const quote = (s: string) => JSON.stringify(s);

function claudeFile(g: Group): string {
  const front = g.globs.length
    ? `---\npaths:\n${g.globs.map((p) => `  - ${quote(p)}`).join("\n")}\n---\n`
    : "";
  return `${front}${NOTICE}\n\n${body(g, true)}`;
}

function cursorFile(g: Group): string {
  const front = g.globs.length
    ? `---\ndescription: ${heading(g.area)}\nglobs: ${g.globs.join(", ")}\nalwaysApply: false\n---\n`
    : `---\ndescription: ${heading(g.area)}\nalwaysApply: true\n---\n`;
  return `${front}${NOTICE}\n\n${body(g, true)}`;
}

function copilotFile(g: Group): string {
  return `---\napplyTo: ${quote(g.globs.join(","))}\n---\n${NOTICE}\n\n${body(g, true)}`;
}

const block = (text: string) => `${BLOCK_START}\n${text.trimEnd()}\n${BLOCK_END}`;

/**
 * Renders accepted entries as each tool's native rules files: one file per area where the tool
 * supports path scoping, and a marked block in the shared files. Pure; `kbx export` writes them.
 */
export function exportRules(
  entries: readonly Entry[],
  targets: readonly ExportTarget[],
): ExportOutput {
  const all = groups(entries);
  const out: ExportOutput = { owned: {}, ownedDirs: [], blocks: {} };
  const want = new Set(targets);

  if (want.has("claude")) {
    out.ownedDirs.push(OWNED_DIRS.claude);
    for (const g of all) out.owned[`${OWNED_DIRS.claude}/${g.area}.md`] = claudeFile(g);
  }
  if (want.has("cursor")) {
    out.ownedDirs.push(OWNED_DIRS.cursor);
    for (const g of all) out.owned[`${OWNED_DIRS.cursor}/${g.area}.mdc`] = cursorFile(g);
  }
  if (want.has("copilot")) {
    out.ownedDirs.push(OWNED_DIRS.copilot);
    const always = all.filter((g) => g.globs.length === 0);
    for (const g of all.filter((x) => x.globs.length > 0)) {
      out.owned[`${OWNED_DIRS.copilot}/${g.area}.instructions.md`] = copilotFile(g);
    }
    // github.com Chat reads only this file, so the always-on rules live here.
    out.blocks[BLOCK_FILES.copilot] = always.length
      ? block(always.map((g) => body(g, true)).join("\n"))
      : "";
  }
  if (want.has("agents-md")) {
    out.blocks[BLOCK_FILES.agentsMd] = all.length
      ? block(all.map((g) => body(g, true)).join("\n"))
      : "";
  }
  return out;
}
