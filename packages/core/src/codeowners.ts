import { CORE_AREA } from "./check.ts";
import { CONFIG_FILE, type Config } from "./config.ts";
import { error, type Issue } from "./issues.ts";
import type { Frontmatter } from "./schema.ts";

export const CODEOWNERS_FILE = "CODEOWNERS";

const HEADER = `# Generated by kbx from ${CONFIG_FILE} and knowledge/. Do not edit; run \`kbx codeowners\`.`;

/**
 * Builds the KB repo's CODEOWNERS. Seniors own everything by default and the config; each
 * `knowledge/<area>/` is owned by the members who list that area, or by the seniors when none
 * do; an entry whose `owner` is not already an area owner gets its own line. Later lines win,
 * so specific rules come after general ones. Pure; the CLI writes the file.
 */
export function generateCodeowners(
  config: Config,
  entries: readonly Frontmatter[],
): { text: string; issues: Issue[] } {
  const issues: Issue[] = [];
  const members = config.team.members;
  const missingHandle = new Set<string>();
  const handles = (ids: readonly string[]) =>
    ids.flatMap((id) => {
      const handle = members.find((m) => m.id === id)?.handle;
      if (!handle) missingHandle.add(id);
      return handle ? [handle] : [];
    });

  const seniors = members.filter((m) => m.role === "senior").map((m) => m.id);
  if (seniors.length === 0) {
    issues.push(
      error("codeowners.noSeniors", "no member has role senior, so nobody would own kbx.yaml", {
        file: CONFIG_FILE,
      }),
    );
  }

  const areaOwners = new Map<string, string[]>();
  for (const area of [CORE_AREA, ...Object.keys(config.areas)].sort()) {
    const listed = members.filter((m) => m.areas.includes(area)).map((m) => m.id);
    areaOwners.set(area, listed.length ? listed : seniors);
  }

  const rules: [string, string[]][] = [
    ["*", seniors],
    [`/${CONFIG_FILE}`, seniors],
    ...[...areaOwners].map(([area, ids]): [string, string[]] => [`/knowledge/${area}/`, ids]),
  ];

  const sorted = [...entries].sort((a, b) =>
    `${a.area}/${a.id}`.localeCompare(`${b.area}/${b.id}`),
  );
  for (const e of sorted) {
    const owners = areaOwners.get(e.area) ?? seniors;
    if (!owners.includes(e.owner)) {
      rules.push([`/knowledge/${e.area}/${e.id}.md`, [e.owner, ...owners]]);
    }
  }

  const lines = rules
    .filter(([, ids]) => ids.length > 0)
    .map(([path, ids]) => [path, handles(ids).join(" ")] as const);

  for (const id of [...missingHandle].sort()) {
    issues.push(
      error("codeowners.handle.missing", `team member "${id}" owns files but has no handle`, {
        path: "team.members",
        file: CONFIG_FILE,
      }),
    );
  }

  const width = Math.max(...lines.filter(([p]) => !p.endsWith(".md")).map(([p]) => p.length));
  const body = lines.map(([path, owners]) =>
    path.endsWith(".md") ? `${path} ${owners}` : `${path.padEnd(width)} ${owners}`,
  );
  return { text: [HEADER, "", ...body, ""].join("\n"), issues };
}
